const assert=require('node:assert/strict');
const fs=require('node:fs');
const l=require('../assets/js/i18n-core.js');
const {extractJsSegments}=require('./bulk-i18n-lib.js');
const memory={value:null,getItem(){return this.value;},setItem(_key,val){this.value=val;}};
assert.equal(l.normalize('de-CH'),'de');
assert.equal(l.normalize('en_US'),'en');
assert.equal(l.normalize('fr-FR'),null);
assert.equal(l.preferred(memory,['fr-FR','de-DE','en-US']),'de');
assert.equal(l.preferred(memory,['fr-FR']),'tr');
assert.equal(l.setPreference(memory,'en'),true);
assert.equal(l.preferred(memory,['de-DE']),'en');
assert.equal(l.languageFromPath('/en/'),'en');
assert.equal(l.languageFromPath('/de/'),'de');
assert.equal(l.languageFromPath('/de/blue-card/'),'de');
assert.equal(l.languageFromPath('/en/chancenkarte-firsat-karti/'),'en');
assert.equal(l.equivalent('/blue-card/','de'),'/de/blue-card/');
assert.equal(l.equivalent('/en/blue-card/','tr'),'/blue-card/');
assert.equal(l.equivalent('/chancenkarte-firsat-karti/','en'),'/en/chancenkarte-firsat-karti/');
assert.equal(l.equivalent('/haberler/vergi-kindergeld-2027/','de'),'/de/haberler/vergi-kindergeld-2027/');
assert.equal(l.equivalent('/en/unsupported-page/','de'),'/de/');
assert.equal(l.equivalent('/en/kindergeld/?source=nav#eligibility','de'),'/de/kindergeld/?source=nav#eligibility');
assert.equal(l.equivalent('/haberler/vergi-kindergeld-2027/?utm_source=mail','en'),'/en/haberler/vergi-kindergeld-2027/?utm_source=mail');
assert.equal(l.equivalent('/de/blue-card/#requirements','tr'),'/blue-card/#requirements');
assert.equal(l.equivalent('/en/unsupported-page/?source=nav#top','de'),'/de/?source=nav#top');
assert.equal(l.home('en'),'/en/');
assert.equal(l.home('de'),'/de/');
assert.equal(l.home('fr'),'/');
const names=[['index.html','tr','/'],['en/index.html','en','/en/'],['de/index.html','de','/de/']];
for(const [path,lang,uri] of names){
 const html=fs.readFileSync(path,'utf8');
 assert.ok(html.includes('lang="'+lang+'"'),path+' lang');
 assert.ok(html.includes('<link rel="canonical" href="https://almanyapusulasi.de'+uri+'">'),path+' canonical');
 for(const [l,u] of [['tr','/'],['en','/en/'],['de','/de/']])
   assert.ok(html.includes('hreflang="'+l+'" href="https://almanyapusulasi.de'+u+'"'),path+' '+l+' hreflang');
}
const shell=fs.readFileSync('assets/js/analytics-consent.js','utf8');
for(const asset of ['i18n-core.js','i18n-ui.js','i18n.css'])assert.ok(shell.includes(asset),'Shared shell missing '+asset);
const ui=fs.readFileSync('assets/js/i18n-ui.js','utf8');
assert.ok(ui.includes('link.href=api.equivalent(path,code)'),'Flag links must keep the current article across locales');
for(const code of ['tr','en','de'])assert.ok(ui.includes(code+':\'<svg'), 'Missing flag SVG '+code);
assert.ok(ui.includes('aria-current'),'Current language not indicated');
assert.ok(ui.includes('aria-label'),'Accessible flag names missing');
assert.ok(!ui.includes('document.createElement("select")'),'Dropdown still present');
assert.ok(ui.includes('location.replace(api.home(pref)'),'Browser preference not routed');
const css=fs.readFileSync('assets/i18n.css','utf8');
assert.ok(css.includes('@media(max-width:650px)'),'Mobile CSS absent');
assert.ok(css.includes('.ap-lang-flag.is-current'),'Active flag styling missing');
assert.ok(css.includes('.site-header .ap-lang-picker{background:transparent;border:0'),'Header language selector should have transparent background');
assert.ok(ui.includes('header.appendChild(box)'),'Flags must be appended to the header right');
for(const part of ['primary-nav-links','nav-mega','ap-secondary-nav','footer-grid','mobile-menu-toggle','aria-expanded','ap-tr-indicator'])assert.ok(ui.includes(part),'Translated shell missing '+part);
assert.ok(ui.includes('unresolved'),'Untranslated destinations must be identified');
for(const label of ['Privacy policy','Datenschutzerklärung','Legal notice','Impressum'])assert.ok(ui.includes(label),'Missing localized legal footer label: '+label);
assert.ok(ui.includes('ap-tr-indicator')&&ui.includes('untranslated?'), 'Turkish fallback links must show a visible TR indicator');
assert.ok(!ui.includes('hero.prepend(box)'),'Flags must not appear inside the banner');
assert.ok(css.includes('.site-header .ap-lang-header{order:10'),'Desktop header order missing');
assert.ok(css.includes('@media(max-width:1080px)'),'Mobile header layout absent');
const jsSegments=extractJsSegments("const html=`<button>Hesapla</button>${items.map(x=>'<span>'+x+'</span>').join('')}`;function collect(){return {name:'İsimsiz şehir'}}");
assert.ok(jsSegments.some(item=>item.source==='Hesapla'),'Template UI text was not extracted');
assert.ok(jsSegments.some(item=>item.source==='İsimsiz şehir'),'Nested JavaScript UI text was not extracted');
assert.ok(jsSegments.every(item=>!item.source.includes('function collect')),'JavaScript code was mistaken for runtime UI text');
console.log('i18n foundation checks passed: language normalization, preferences, routes, SEO, shell and responsive CSS.');
